int __io_putchar(int ch)
{
  if ( ch == '\n' )
	  HAL_UART_Transmit(&huart1, (uint8_t*)&"\r", 1, HAL_MAX_DELAY);
  HAL_UART_Transmit(&huart1, (uint8_t*)&ch, 1, HAL_MAX_DELAY);
  return ch;
}

int __io_getchar(void)
{
	uint8_t ch;

	while( HAL_UART_Receive(&huart1, &ch, 1, HAL_MAX_DELAY) != HAL_OK)
	{
		;
	}
	return ch;
}

static HAL_StatusTypeDef lcdWrite(const LcdInitCommand *item)
{
  HAL_GPIO_WritePin(WRX_DCX_GPIO_Port, WRX_DCX_Pin, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(CSX_GPIO_Port, CSX_Pin, GPIO_PIN_RESET);

  if (HAL_SPI_Transmit(&hspi5, (uint8_t *)&item->command, 1U, HAL_MAX_DELAY) != HAL_OK)
  {
    HAL_GPIO_WritePin(CSX_GPIO_Port, CSX_Pin, GPIO_PIN_SET);
    return HAL_ERROR;
  }

  if (item->length > 0U)
  {
    HAL_GPIO_WritePin(WRX_DCX_GPIO_Port, WRX_DCX_Pin, GPIO_PIN_SET);
    if (HAL_SPI_Transmit(&hspi5, (uint8_t *)item->data, item->length, HAL_MAX_DELAY) != HAL_OK)
    {
      HAL_GPIO_WritePin(CSX_GPIO_Port, CSX_Pin, GPIO_PIN_SET);
      return HAL_ERROR;
    }
  }

  HAL_GPIO_WritePin(CSX_GPIO_Port, CSX_Pin, GPIO_PIN_SET);

  if (item->delay > 0U)
  {
    HAL_Delay(item->delay);
  }

  return HAL_OK;
}

static HAL_StatusTypeDef sdramInitSequence(void)
{
  FMC_SDRAM_CommandTypeDef command = {0};

  command.CommandTarget = FMC_SDRAM_CMD_TARGET_BANK2;
  command.AutoRefreshNumber = 1U;

  command.CommandMode = FMC_SDRAM_CMD_CLK_ENABLE;
  if (HAL_SDRAM_SendCommand(&hsdram1, &command, SDRAM_TIMEOUT) != HAL_OK)
  {
    return HAL_ERROR;
  }

  HAL_Delay(1U);

  command.CommandMode = FMC_SDRAM_CMD_PALL;
  if (HAL_SDRAM_SendCommand(&hsdram1, &command, SDRAM_TIMEOUT) != HAL_OK)
  {
    return HAL_ERROR;
  }

  command.CommandMode = FMC_SDRAM_CMD_AUTOREFRESH_MODE;
  command.AutoRefreshNumber = 4U;
  if (HAL_SDRAM_SendCommand(&hsdram1, &command, SDRAM_TIMEOUT) != HAL_OK)
  {
    return HAL_ERROR;
  }

  command.CommandMode = FMC_SDRAM_CMD_LOAD_MODE;
  command.AutoRefreshNumber = 1U;
  command.ModeRegisterDefinition = 0x0230U;
  if (HAL_SDRAM_SendCommand(&hsdram1, &command, SDRAM_TIMEOUT) != HAL_OK)
  {
    return HAL_ERROR;
  }

  return HAL_SDRAM_ProgramRefreshRate(&hsdram1, SDRAM_REFRESH_COUNT);
}

static HAL_StatusTypeDef lcdInit(void)
{
  HAL_GPIO_WritePin(NCS_MEMS_SPI_GPIO_Port, NCS_MEMS_SPI_Pin, GPIO_PIN_SET);
  HAL_GPIO_WritePin(CSX_GPIO_Port, CSX_Pin, GPIO_PIN_SET);

  for (uint32_t i = 0U; i < sizeof(lcdInitSequence) / sizeof(lcdInitSequence[0]); ++i)
  {
    if (lcdWrite(&lcdInitSequence[i]) != HAL_OK)
    {
      return HAL_ERROR;
    }
  }

  lcdFill(LCD_COLOR_BLACK);
  return HAL_OK;
}

void lcdFill(uint16_t color)
{
  volatile uint16_t *framebuffer = (volatile uint16_t *)LCD_FRAMEBUFFER_ADDRESS;

  for (uint32_t i = 0U; i < LCD_WIDTH * LCD_HEIGHT; ++i)
  {
    framebuffer[i] = color;
  }
}

